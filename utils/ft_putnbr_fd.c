#include "../push_swap.h"

void	ft_putnbr_fd(int fd, int n)
{
	char	c;

	if (n == 0)
	{
		write(fd, "0", 1);
		return ;
	}
	if (n < 0)
	{
		write(fd, "-", 1);
		n = -n;
	}
	if (n > 9)
		ft_putnbr_fd(fd, n / 10);
	c = (n % 10) + '0';
	write(fd, &c, 1);
}
